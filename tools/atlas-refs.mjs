#!/usr/bin/env node
// Rewrites src/camera-references/data.js from a local cinematic-atlas checkout:
//
//   ATLAS_DIR=<atlas checkout> node tools/atlas-refs.mjs [--out <file>]
//
// It reads the atlas's book list (data/books.json: id, title, author, year,
// section titles) and its camera-page tags (data/camera-showcases.json: book,
// page, tags, evidence terms), scores every page of the citable books
// (atlas-refs-table.mjs) against each technique, coverage pattern and cut
// rule, and writes at most three books with two pages each per entry.
// Nothing but citations leaves this tool: no page text, excerpt, image or
// file name. The output is sorted and stable: the same atlas gives the same bytes.
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { TECHNIQUES } from "../src/camera-techniques/index.js";
import { COVERAGE_PATTERN_IDS } from "../src/camera-coverage/patterns.js";
import { CUT_RULES } from "../src/camera-coverage/cut-rules.js";
import { BOOKS, TABLE } from "./atlas-refs-table.mjs";

const MAX_BOOKS = 3, MAX_PAGES = 2, MIN_SCORE = 2;
const SECTIONS = { techniques: TECHNIQUES.map((entry) => entry.id), patterns: [...COVERAGE_PATTERN_IDS], cuts: [...CUT_RULES] };

const args = process.argv.slice(2);
const outArg = args.includes("--out") ? args[args.indexOf("--out") + 1] : null;
const atlasDir = process.env.ATLAS_DIR;
if (!atlasDir) {
	console.error("Set ATLAS_DIR to a local cinematic-atlas checkout.");
	process.exit(2);
}
const out = outArg ? resolve(outArg) : fileURLToPath(new URL("../src/camera-references/data.js", import.meta.url));
const readJson = (path) => JSON.parse(readFileSync(join(atlasDir, "data", path), "utf8"));

const atlasBooks = new Map(readJson("books.json").map((book) => [book.id, book]));
const order = new Map(BOOKS.map((book, index) => [book.id, index]));
const sectionTitle = (book, page) => {
	let title = "";
	for (const chapter of [...(book.chapters ?? [])].sort((a, b) => a.page - b.page)) if (chapter.page <= page) title = String(chapter.title ?? "");
	return title.toLowerCase();
};
const wordIn = (text, phrase) => new RegExp(`(^|[^a-z0-9])${phrase.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}($|[^a-z0-9])`).test(text);

// Every page of a citable book, reduced to what scoring needs.
const pages = readJson("camera-showcases.json").entries
	.filter((entry) => order.has(entry.bookId) && atlasBooks.has(entry.bookId) && Number.isInteger(entry.page) && entry.page > 0)
	.map((entry) => ({ book: entry.bookId, page: entry.page, tags: new Set(entry.tags ?? []), high: entry.confidence === "high",
		terms: new Set((entry.evidence ?? []).map((term) => String(term).toLowerCase())), section: sectionTitle(atlasBooks.get(entry.bookId), entry.page) }));

function score(page, row) {
	const hits = 3 * row.terms.filter((term) => page.terms.has(term)).length + 2 * row.sections.filter((phrase) => wordIn(page.section, phrase)).length;
	if (hits < MIN_SCORE) return 0;
	return hits + row.tags.filter((tag) => page.tags.has(tag)).length + (page.high ? 0.5 : 0);
}

function refsFor(row) {
	const ranked = pages.map((page) => ({ page, value: score(page, row) })).filter((item) => item.value > 0)
		.sort((a, b) => b.value - a.value || order.get(a.page.book) - order.get(b.page.book) || a.page.page - b.page.page);
	const byBook = new Map();
	for (const { page } of ranked) {
		if (!byBook.has(page.book) && byBook.size >= MAX_BOOKS) continue;
		const list = byBook.get(page.book) ?? [];
		if (list.length < MAX_PAGES) byBook.set(page.book, [...list, page.page]);
	}
	return [...byBook].map(([book, list]) => ({ book, pages: list.sort((a, b) => a - b) }));
}

const refs = {}, none = {};
for (const [section, ids] of Object.entries(SECTIONS)) {
	const table = TABLE[section] ?? {};
	const unknown = Object.keys(table).filter((id) => !ids.includes(id));
	if (unknown.length) throw new Error(`atlas-refs-table.mjs ${section} names ids the catalog does not have: ${unknown.join(", ")}`);
	refs[section] = {}; none[section] = [];
	for (const id of ids) {
		const list = table[id] ? refsFor(table[id]) : [];
		if (list.length) refs[section][id] = list; else none[section].push(id);
	}
}

const cited = new Set(Object.values(refs).flatMap((rows) => Object.values(rows).flat().map((ref) => ref.book)));
const books = BOOKS.filter((book) => cited.has(book.id)).map(({ id, edition }) => {
	const atlas = atlasBooks.get(id);
	return { id, title: String(atlas.title), author: String(atlas.author), edition, year: Number(atlas.published) || null };
});

const q = JSON.stringify;
const lines = [
	"// Generated by tools/atlas-refs.mjs from a local cinematic-atlas checkout (camera and directing books only).",
	"// Citations only: book id, title, author, edition, year, pages (the atlas reader's page numbers).",
	"// Do not edit by hand; rerun: ATLAS_DIR=<atlas checkout> node tools/atlas-refs.mjs",
	"",
	"export const REFERENCE_BOOKS = [",
	...books.map((book) => `\t{ id: ${q(book.id)}, title: ${q(book.title)}, author: ${q(book.author)}, edition: ${q(book.edition)}, year: ${q(book.year)} },`),
	"];",
	"",
	"export const REFERENCES = {",
	...Object.entries(refs).flatMap(([section, rows]) => [`\t${section}: {`,
		...Object.entries(rows).map(([id, list]) => `\t\t${q(id)}: [${list.map((ref) => `{ book: ${q(ref.book)}, pages: [${ref.pages.join(", ")}] }`).join(", ")}],`), "\t},"]),
	"};",
	"",
	"/** Entries the atlas has no page for: listed so the coverage check can tell a gap from an omission. */",
	"export const NO_REFERENCES = {",
	...Object.entries(none).map(([section, ids]) => `\t${section}: [${ids.map(q).join(", ")}],`),
	"};",
	"",
];
writeFileSync(out, lines.join("\n"));
const count = (rows) => Object.values(rows).reduce((sum, section) => sum + Object.keys(section).length, 0);
console.log(`atlas-refs: ${count(refs)} entries with references, ${Object.values(none).flat().length} without, ${books.length} books -> ${outArg ?? "src/camera-references/data.js"}`);
